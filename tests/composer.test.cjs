const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { createAttachments, materializeMessages, codexInput } = require('../electron/attachments.cjs')
const { createComposerCatalog, preparePrompt } = require('../electron/composer.cjs')
const png = Buffer.from('fixture-png')
async function temp(t) { const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'zai-composer-')); t.after(() => fs.rm(dir, { recursive: true, force: true })); return dir }
test('adjuntos privados validan imágenes, límites y rutas, y se adaptan a cada protocolo', async (t) => {
  const directory = await temp(t)
  const store = createAttachments({ directory, nativeImage: { createFromBuffer: () => ({ isEmpty: () => false, getSize: () => ({ width: 16, height: 16 }), toPNG: () => png }) } })
  const image = { ...await store.import({ name: 'test.png', dataUrl: 'data:image/png;base64,aGVsbG8=' }), reference: 'imagen1' }
  const resolved = await store.resolve([image])
  assert.deepEqual(await store.read(image.id), png)
  await assert.rejects(store.read('../outside.png'), /inválida/)
  await assert.rejects(store.import({ dataUrl: 'data:text/html;base64,aGVsbG8=' }), /Usa una imagen/)
  await assert.rejects(store.resolve([image, image]), /repetidas/)
  await assert.rejects(store.resolve(Array(9).fill(image)), /máximo/)
  await assert.rejects(store.resolve([{ ...image, reference: '../../x' }]), /Referencia/)
  const messages = [{ role: 'user', content: [{ type: 'text', text: 'Mira @imagen1' }, { type: 'zai_image', ...image }] }]
  const open = await materializeMessages(messages, { kind: 'openrouter' }, store)
  assert.equal(open[0].content.at(-1).type, 'image_url')
  assert.match(open[0].content.at(-1).image_url.url, /^data:image\/png;base64,/)
  const ollama = await materializeMessages(messages, { kind: 'ollama-local' }, store)
  assert.equal(ollama[0].images[0], png.toString('base64')); assert.match(ollama[0].content, /@imagen1/)
  assert.equal(JSON.stringify(messages).includes(png.toString('base64')), false)
  const codex = codexInput('Mira', resolved, [{ name: 'test', path: '/skills/test/SKILL.md' }])
  assert.equal(codex[2].type, 'localImage'); assert.equal(codex[2].path, resolved[0].path)
  assert.equal(codex[3].type, 'skill')
  await fs.writeFile(path.join(directory, 'empty.png'), '')
  if (process.platform !== 'win32') {
    const linked = '11111111-1111-1111-1111-111111111111.png'; await fs.symlink(path.join(directory, image.id), path.join(directory, linked))
    await assert.rejects(store.read(linked), /no disponible/)
  }
})
test('menciones de archivos quedan dentro del proyecto y skills seleccionadas se despachan por agente', async (t) => {
  const cwd = await temp(t), catalog = createComposerCatalog(); t.after(() => catalog.dispose())
  await fs.mkdir(path.join(cwd, '.zai/skills/probe'), { recursive: true })
  await fs.writeFile(path.join(cwd, '.zai/skills/probe/SKILL.md'), '---\nname: probe\ndescription: Fixture skill\n---\nRead the requested file and report findings.')
  await fs.mkdir(path.join(cwd, 'src')); await fs.writeFile(path.join(cwd, 'src/file with spaces.ts'), 'export const hello = 1')
  await fs.writeFile(path.join(cwd, '.env'), 'FAKE_SECRET=fixture')
  const options = await catalog.get('zai', cwd)
  assert.equal(options.skills.some((s) => s.name === 'probe'), true)
  assert.equal((await catalog.files(cwd, 'file')).includes('src/file with spaces.ts'), true)
  assert.equal((await catalog.files(cwd)).includes('.env'), false)
  const text = '$probe revisa @"src/file with spaces.ts"'
  const result = await preparePrompt(text, 'zai', cwd, options, ['src/file with spaces.ts'])
  assert.match(result.text, /export const hello = 1/); assert.match(result.text, /Read the requested file/)
  assert.equal((await preparePrompt('$probe revisa', 'claude', cwd, options)).text, '/probe revisa')
  assert.equal((await preparePrompt('$probe-more', 'codex', cwd, options)).skills.length, 0)
  await assert.rejects(preparePrompt('@src/file.tsx', 'codex', cwd, options, ['src/file.ts']), /Mención/)
  await assert.rejects(preparePrompt('@../outside.txt', 'codex', cwd, options, ['../outside.txt']), /dentro del proyecto/)
  await fs.writeFile(path.join(cwd, 'binary'), Buffer.from([0, 1, 2]))
  await assert.rejects(preparePrompt('@binary', 'zai', cwd, options, ['binary']), /deben ser texto/)
})
