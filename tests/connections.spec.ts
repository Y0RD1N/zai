import { expect, test } from '@playwright/test'
import { chooseOption } from './select'

test('arrastrar un punto crea un hilo que sigue a las ventanas y se guarda', async ({ page }) => {
  await page.goto('/')
  const browser = page.getByLabel('Conectar Navegador · lado derecho', { exact: true })
  const codex = page.getByLabel('Conectar Codex · lado izquierdo', { exact: true })
  const start = (await browser.boundingBox())!, end = (await codex.boundingBox())!
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
  await page.mouse.down()
  await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 12 })
  await page.mouse.up()
  const wire = page.getByTestId('browser-connection')
  await expect(wire).toHaveCount(1)
  const path = await wire.locator('.connection-stroke').getAttribute('d')
  const title = (await page.getByTestId('panel-browser').locator('.panel-titlebar').boundingBox())!
  await page.mouse.move(title.x + 110, title.y + 20)
  await page.mouse.down()
  await page.mouse.move(title.x + 180, title.y - 20, { steps: 6 })
  await page.mouse.up()
  await expect(wire.locator('.connection-stroke')).not.toHaveAttribute('d', path!)
  await expect(page.locator('.connection-pulses')).toHaveCount(0)
  await page.getByText('Guardado localmente', { exact: true }).waitFor()
  await page.reload()
  await expect(wire).toHaveCount(1)
  await page.getByRole('button', { name: 'Minimizar Navegador', exact: true }).click()
  await expect(wire).toHaveCount(1)
  await page.getByRole('button', { name: 'Conexión Codex con Navegador', exact: true }).focus()
  await page.keyboard.press('Delete')
  await expect(wire).toHaveCount(0)
})

test('los puntos también se conectan con teclado y no conectan dos agentes', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Conectar Codex · lado derecho', { exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.getByLabel('Conectar Claude · lado izquierdo', { exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('browser-connection')).toHaveCount(0)
  await page.getByLabel('Conectar Navegador · lado izquierdo', { exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('browser-connection')).toHaveCount(1)
  await page.getByRole('button', { name: 'Cerrar Navegador', exact: true }).click()
  await expect(page.getByTestId('browser-connection')).toHaveCount(0)
})

test('los permisos nativos de cada proveedor sobreviven a la recarga', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Configurar permisos de Codex', exact: true }).click()
  await chooseOption(page, 'Acceso a archivos de Codex', 'read-only')
  await chooseOption(page, 'Aprobaciones de Codex', 'never')
  await page.getByLabel('Red de los comandos de Codex', { exact: true }).check()
  await page.getByRole('button', { name: 'Cerrar configuración de Codex', exact: true }).click()
  await page.getByRole('button', { name: 'Configurar permisos de Claude', exact: true }).click()
  await chooseOption(page, 'Modo de permisos de Claude', 'acceptEdits')
  await chooseOption(page, 'Permisos del navegador de Claude', 'control')
  await page.getByText('Guardado localmente', { exact: true }).waitFor()
  await page.reload()
  await page.getByRole('button', { name: 'Configurar permisos de Codex', exact: true }).click()
  await expect(page.getByLabel('Acceso a archivos de Codex', { exact: true })).toHaveAttribute('data-value', 'read-only')
  await expect(page.getByLabel('Aprobaciones de Codex', { exact: true })).toHaveAttribute('data-value', 'never')
  await expect(page.getByLabel('Red de los comandos de Codex', { exact: true })).toBeChecked()
  await page.getByRole('button', { name: 'Cerrar configuración de Codex', exact: true }).click()
  await page.getByRole('button', { name: 'Configurar permisos de Claude', exact: true }).click()
  await expect(page.getByLabel('Modo de permisos de Claude', { exact: true })).toHaveAttribute('data-value', 'acceptEdits')
  await expect(page.getByLabel('Permisos del navegador de Claude', { exact: true })).toHaveAttribute('data-value', 'control')
})
